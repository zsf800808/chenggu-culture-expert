DIGITS = "零一二三四五六七八九"
BRANCH = "子丑寅卯辰巳午未申酉戌亥"


def normalize_hour(hour):
    """把用户输入归一化成十二时辰键，如 '辰时'/'辰'/'辰时(7-9)' -> '辰时'。"""
    if not hour:
        return None
    for ch in hour:
        if ch in BRANCH:
            return ch + "时"
    return None


def ganzhi_index(year):
    """公历年份 -> 六十甲子索引。"""
    return ((int(year) - 4) % 60 + 60) % 60


def qian_to_text(total_qian):
    """整数钱 -> 中文几两几钱。"""
    liang = total_qian // 10
    qian = total_qian % 10
    if qian == 0:
        return DIGITS[liang] + "两整"
    return DIGITS[liang] + "两" + DIGITS[qian] + "钱"


def get_level(total_liang):
    for lv in GU_LEVELS:
        if lv["min"] <= total_liang <= lv["max"]:
            return lv
    return GU_LEVELS[0]


def calc(year, month, day, hour):
    """核心计算，返回结果 dict。"""
    # 校验
    month = int(month)
    day = int(day)
    if not (1 <= month <= 12):
        raise ValueError("农历月份必须在 1-12 之间")
    if not (1 <= day <= 30):
        raise ValueError("农历日期必须在 1-30 之间")
    hkey = normalize_hour(hour)
    if hkey is None:
        raise ValueError("时辰无效，须为十二时辰之一（子/丑/寅/卯/辰/巳/午/未/申/酉/戌/亥时）")

    gi = ganzhi_index(year)
    gz = JIAZI[gi]

    # 用整数「钱」计算，避免浮点误差
    y_qian = int(round(YEAR_W[gi] * 10))
    m_qian = int(round(MONTH_W[month - 1] * 10))
    d_qian = int(round(DAY_W[day - 1] * 10))
    h_qian = int(round(HOUR_W[hkey] * 10))
    total_qian = y_qian + m_qian + d_qian + h_qian

    total_liang = total_qian / 10.0
    key = "%d.%d" % (total_qian // 10, total_qian % 10)
    ge = GE.get(key, "")

    return {
        "year": int(year),
        "month": month,
        "day": day,
        "hour": hkey,
        "ganzhi": gz,
        "ganzhi_index": gi,
        "weights": {
            "year": YEAR_W[gi],
            "month": MONTH_W[month - 1],
            "day": DAY_W[day - 1],
            "hour": HOUR_W[hkey],
        },
        "weight_labels": {
            "year": gz,
            "month": MONTH_NAMES[month - 1],
            "day": DAY_NAMES[day - 1],
            "hour": hkey + "(" + HOUR_NAMES[hkey] + ")",
        },
        "total_qian": total_qian,
        "total": total_liang,
        "total_text": qian_to_text(total_qian),
        "ge": ge,
        "level": get_level(total_liang),
    }


def main():
    parser = argparse.ArgumentParser(description="传统称骨确定性查表计算")
    parser.add_argument("--year", type=int, help="公历出生年份")
    parser.add_argument("--month", type=int, help="农历月份 1-12")
    parser.add_argument("--day", type=int, help="农历日期 1-30")
    parser.add_argument("--hour", help="出生时辰（子时~亥时）")
    parser.add_argument("--json", dest="json_input", help='JSON 输入 {"year":..,"month":..,"day":..,"hour":".."}')

    args = parser.parse_args()

    if args.json_input:
        data = json.loads(args.json_input)
        year = data["year"]
        month = data["month"]
        day = data["day"]
        hour = data["hour"]
    else:
        year = args.year
        month = args.month
        day = args.day
        hour = args.hour

    if year is None or month is None or day is None or hour is None:
        print(json.dumps({"error": "缺少参数，需要 year/month/day/hour"}, ensure_ascii=False))
        sys.exit(1)

    try:
        result = calc(year, month, day, hour)
    except ValueError as e:
        print(json.dumps({"error": str(e)}, ensure_ascii=False))
        sys.exit(1)

    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
